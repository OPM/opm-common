#ifndef MSW_TRACKER_HPP
#define MSW_TRACKER_HPP

#include <opm/common/OpmLog/KeywordLocation.hpp>

#include <cstddef>
#include <map>
#include <optional>
#include <set>
#include <string>
#include <unordered_map>
#include <utility>
#include <vector>

namespace Opm {

class Well;

/// Keyword-level bookkeeping of the data that defines multi-segmented
/// wells, for the purpose of verifying that the data entered across the
/// WELSPECS, COMPDAT, WELSEGS, COMPSEGS, and COMPTRAJ keywords is
/// internally consistent.
///
/// Connections are identified by the linearised Cartesian index of the
/// connection's cell (i + Nx*(j + Ny*k) for zero-based IJK indices) in the
/// grid of the well.
///
/// The tracker records, for each well,
///
///   * all connections entered in COMPDAT (or generated by COMPTRAJ)
///   * all segment numbers entered in WELSEGS (or generated by COMPTRAJ)
///   * all connection-to-segment links entered in COMPSEGS (or generated
///     by COMPTRAJ)
///
/// and reports, for multi-segmented wells only, connections without an
/// associated segment and connections linked to segments that do not exist.
class MswTracker
{
public:
    /// Linearised Cartesian cell index of a connection.
    using CellIndex = std::size_t;

    /// Association between a single connection and a single segment.
    struct Link
    {
        /// Connection's cell.
        CellIndex cell{};

        /// Segment number to which the connection is attached.
        int segment{};
    };

    /// Kind of inconsistency detected in a multi-segmented well.
    enum class ProblemKind {
        /// Connection not attached to any segment.
        UnlinkedConnection,

        /// Connection attached to a segment number that has not been
        /// defined in WELSEGS.
        UnknownSegment,

        /// Connection attached to multiple distinct segments within a
        /// single COMPSEGS keyword.
        MultiplyLinked,
    };

    /// Single inconsistency detected in a multi-segmented well.
    struct Problem
    {
        /// Name of well with inconsistent data.
        std::string well{};

        /// Kind of inconsistency.
        ProblemKind kind{ProblemKind::UnlinkedConnection};

        /// Connection's cell.
        CellIndex cell{};

        /// Segment numbers.  Empty for UnlinkedConnection problems, a
        /// single element for UnknownSegment problems, and all distinct
        /// segments, in order of appearance, for MultiplyLinked problems.
        std::vector<int> segments{};

        /// Location of the keyword that introduced the problem.  The
        /// connection keyword (COMPDAT) for UnlinkedConnection problems
        /// and the segment association keyword (COMPSEGS) otherwise.
        /// Empty location if the information originates from a restart
        /// file.
        KeywordLocation location{};
    };

    /// \brief Whether or not a well is known to the tracker.
    ///
    /// \param[in] well Well name.
    bool isKnown(const std::string& well) const;

    /// \brief Mark a well as defined.
    ///
    /// Typically called from the WELSPECS/WELSPECL keyword handlers.
    /// Redefining an existing well does not alter its tracked data.
    ///
    /// \param[in] well Well name.
    void defined(const std::string& well);

    /// \brief Initialise tracking data from an existing well object.
    ///
    /// Typically used for wells loaded from a restart file, whose defining
    /// keywords are never seen by the tracker.  No effect if the well is
    /// already known.
    ///
    /// \param[in] well Existing well object.
    void seed(const Well& well);

    /// \brief Register connections for a well.
    ///
    /// Typically called from the COMPDAT/COMPDATL/COMPDATM keyword
    /// handlers.  Cells that are already registered keep the location of
    /// the keyword that first introduced them.
    ///
    /// \param[in] well Well name.
    /// \param[in] cells Connections' cells.
    /// \param[in] location Location of the connection keyword.
    void connections(const std::string&            well,
                     const std::vector<CellIndex>& cells,
                     const KeywordLocation&        location);

    /// \brief Register segment numbers for a well and mark the well as
    /// multi-segmented.
    ///
    /// Typically called from the WELSEGS keyword handler.  Segment numbers
    /// accumulate across multiple calls.
    ///
    /// \param[in] well Well name.
    /// \param[in] segments Segment numbers.
    void segments(const std::string&      well,
                  const std::vector<int>& segments);

    /// \brief Register connection-to-segment links for a well.
    ///
    /// Typically called from the COMPSEGS keyword handler, with one call
    /// for each keyword.  Links replace any existing links for the same
    /// connections from earlier calls.
    ///
    /// \param[in] well Well name.
    /// \param[in] links Connection-to-segment associations.
    /// \param[in] location Location of the association keyword.
    ///
    /// Connections that are linked to more than one distinct segment
    /// within \p links are reported as MultiplyLinked problems in the
    /// next call to checkAndClearDirty().
    void linkConnections(const std::string&       well,
                    const std::vector<Link>& links,
                    const KeywordLocation&   location);

    /// \brief Check consistency of all multi-segmented wells whose data
    /// has changed since the previous call.
    ///
    /// Wells that are not multi-segmented are not checked.
    ///
    /// \return Inconsistencies, grouped by well in order of definition and
    /// sorted by kind and cell index within each well.
    std::vector<Problem> checkAndClearDirty();

private:
    /// Connection-to-segment link with its keyword location.
    struct LinkInfo
    {
        /// Segment number.
        int segment{};

        /// Location of association keyword.
        KeywordLocation location{};
    };

    /// Tracking data for a single well.
    struct WellEntry
    {
        /// Well name.
        std::string name{};

        /// Whether or not the well is multi-segmented.
        bool multiSegment{false};

        /// Whether or not the well's data has changed since the last
        /// consistency check.
        bool dirty{false};

        /// Connections, keyed by cell, with the location of the keyword
        /// that introduced them.
        std::map<CellIndex, KeywordLocation> connections{};

        /// Defined segment numbers.
        std::set<int> segments{};

        /// Connection-to-segment links, keyed by cell.
        std::map<CellIndex, LinkInfo> links{};

        /// Connections linked to multiple distinct segments within a
        /// single association keyword since the last consistency check.
        std::vector<Problem> conflicts{};
    };

    /// Map from well name to index into wells_.
    std::unordered_map<std::string, std::vector<WellEntry>::size_type> index_{};

    /// Tracking data, in order of definition.
    std::vector<WellEntry> wells_{};

    /// \brief Get tracking data for a well.
    ///
    /// \param[in] well Well name.
    ///
    /// \return Tracking data, or nullptr if the well is not known.
    WellEntry* entry(const std::string& well);

    /// \brief Get or create tracking data for a well.
    ///
    /// \param[in] well Well name.
    WellEntry& entryOrNew(const std::string& well);
};

} // namespace Opm

#endif // MSW_TRACKER_HPP
